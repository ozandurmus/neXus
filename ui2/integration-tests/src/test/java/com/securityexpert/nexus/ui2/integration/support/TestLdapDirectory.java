/**
 * A real, in-process LDAPS directory server for the identity tests in
 * {@code identity/} — {@code com.unboundid.ldap.listener.InMemoryDirectoryServer},
 * shipped by the same UnboundID LDAP SDK the repository already depends on
 * for {@code ldap-adapter} (contract §4). It accepts a real TLS connection on
 * the loopback interface, speaks the real LDAP wire protocol, evaluates a
 * real {@code SimpleBindRequest} against a real password, and answers real
 * searches against real directory entries.
 *
 * <p>Since the 2026-11-11 service-bind model (design
 * LDAP_SERVICE_BIND_DESIGN_2026_11_11) {@link UnboundIdOperatorBindAdapter}
 * binds a service account, searches the user by {@code sAMAccountName}, binds
 * as the found entry and admits only a member of the administrators or users
 * group. This harness serves LDAPS with a synthetic CA and {@code localhost}
 * leaf generated by the JDK's own {@code keytool}, seeds AD-shaped user
 * entries, and every person it seeds is a member of {@link #USERS_GROUP_DN}.
 * The in-memory server does not implement AD's extensible matching rules, so
 * an interceptor evaluates LDAP_MATCHING_RULE_IN_CHAIN and the
 * userAccountControl bit test here.</p>
 *
 * <p>Every DN, username, password, key and group here is a synthetic test
 * value invented for this harness (AGENTS.md "no real credentials, no real
 * directory data"). Schema enforcement is disabled so the harness can use a
 * minimal {@code member}-bearing group shape.</p>
 *
 * <p><b>Fail closed, like {@link Ui2PostgresFixture}:</b> if the certificates
 * cannot be generated or the server cannot start, {@link #start()} throws.
 * There is no fallback, no skip, and no faked directory.</p>
 */
public final class TestLdapDirectory implements AutoCloseable {

    public static final String BASE_DN = "dc=example,dc=com";
    public static final String PEOPLE_BASE_DN = "ou=people,dc=example,dc=com";
    public static final String GROUPS_BASE_DN = "ou=groups,dc=example,dc=com";
    /** The users group: every seeded person is in it (role mapping: viewer). */
    public static final String USERS_GROUP_DN = "cn=nexus-users,ou=groups,dc=example,dc=com";
    /** The administrators group: empty until a test adds a member. */
    public static final String ADMIN_GROUP_DN = "cn=nexus-admins,ou=groups,dc=example,dc=com";
    public static final String PROFILE_ID = DirectoryProfile.DEFAULT_PROFILE_ID;
    /** The service account (synthetic); its password is generated per directory. */
    public static final String SERVICE_ACCOUNT_DN = "cn=nexus-service,dc=example,dc=com";

    private static Material material;

    private final InMemoryDirectoryServer server;
    private final DirectoryProfile profile;
    private final char[] servicePassword;

    private TestLdapDirectory(InMemoryDirectoryServer server, DirectoryProfile profile, char[] servicePassword) {
        this.server = server;
        this.profile = profile;
        this.servicePassword = servicePassword;
    }

    /** Starts a fresh, base-structure-seeded LDAPS directory listening on a free loopback port. */
    public static TestLdapDirectory start() {
        try {
            Material tls = material();
            InMemoryDirectoryServerConfig config = new InMemoryDirectoryServerConfig(BASE_DN);
            config.setSchema(null);
            String servicePassword = UUID.randomUUID().toString();
            config.addAdditionalBindCredentials(SERVICE_ACCOUNT_DN, servicePassword);
            AdRules rules = new AdRules();
            config.addInMemoryOperationInterceptor(rules);
            config.setListenerConfigs(InMemoryListenerConfig.createLDAPSConfig("test-ldaps",
                    InetAddress.getLoopbackAddress(), 0, tls.server().getServerSocketFactory(),
                    tls.server().getSocketFactory(), false, false));
            InMemoryDirectoryServer server = new InMemoryDirectoryServer(config);
            rules.server = server;
            server.startListening();
            server.add(new Entry(BASE_DN, new Attribute("objectClass", "top", "domain"),
                    new Attribute("dc", "example")));
            server.add(new Entry(PEOPLE_BASE_DN, new Attribute("objectClass", "top", "organizationalUnit"),
                    new Attribute("ou", "people")));
            server.add(new Entry(GROUPS_BASE_DN, new Attribute("objectClass", "top", "organizationalUnit"),
                    new Attribute("ou", "groups")));
            server.add(new Entry(USERS_GROUP_DN, new Attribute("objectClass", "top", "group"),
                    new Attribute("cn", "nexus-users")));
            server.add(new Entry(ADMIN_GROUP_DN, new Attribute("objectClass", "top", "group"),
                    new Attribute("cn", "nexus-admins")));
            DirectoryProfile profile = new DirectoryProfile(PROFILE_ID, java.util.List.of("localhost"),
                    server.getListenPort(), BASE_DN, ADMIN_GROUP_DN, USERS_GROUP_DN, SERVICE_ACCOUNT_DN, 5, true,
                    DirectoryProfile.TrustMode.TRUST_PEM, Files.readString(tls.caPem()));
            return new TestLdapDirectory(server, profile, servicePassword.toCharArray());
        } catch (java.io.IOException e) {
            throw new IllegalStateException("could not read the synthetic test CA", e);
        } catch (LDAPException e) {
            throw new IllegalStateException(
                    "could not start the in-process test LDAP directory (UnboundID InMemoryDirectoryServer): "
                            + e.getResultCode(), e);
        }
    }

    /** The server-owned profile a production deployment would configure for this directory. */
    public DirectoryProfile profile() {
        return profile;
    }

    /** The production operator-bind adapter over this directory's verified LDAPS profile. */
    public UnboundIdOperatorBindAdapter operatorBindAdapter() {
        return new UnboundIdOperatorBindAdapter(profile, new DirectoryTrustPolicy(profile, () -> { }),
                servicePassword::clone);
    }

    /** The production re-validation adapter, bound as the synthetic service account. */
    public com.securityexpert.nexus.ui2.identity.ldap.UnboundIdRevalidationAdapter revalidationAdapter() {
        return new com.securityexpert.nexus.ui2.identity.ldap.UnboundIdRevalidationAdapter(profile,
                new DirectoryTrustPolicy(profile, () -> { }), servicePassword::clone);
    }

    /**
     * One AD-shaped user under {@link #PEOPLE_BASE_DN} whose {@code sAMAccountName} is {@code cn}, in
     * {@link #USERS_GROUP_DN}. {@code password} is a synthetic test value, never logged.
     */
    public String addPerson(String cn, String password) {
        String dn = "cn=" + cn + "," + PEOPLE_BASE_DN;
        try {
            server.add(new Entry(dn,
                    new Attribute("objectClass", "top", "person", "organizationalPerson", "user"),
                    new Attribute("objectCategory", "person"),
                    new Attribute("cn", cn),
                    new Attribute("sn", cn),
                    new Attribute("sAMAccountName", cn),
                    new Attribute("userAccountControl", "512"),
                    new Attribute("userPassword", password)));
            server.modify(USERS_GROUP_DN, new Modification(ModificationType.ADD, "member", dn));
        } catch (LDAPException e) {
            throw new IllegalStateException("could not seed test directory person entry: " + e.getResultCode(), e);
        }
        return dn;
    }

    /** Adds {@code memberDn} to the administrators group. */
    public void addAdmin(String memberDn) {
        try {
            server.modify(ADMIN_GROUP_DN, new Modification(ModificationType.ADD, "member", memberDn));
        } catch (LDAPException e) {
            throw new IllegalStateException("could not seed the administrators group: " + e.getResultCode(), e);
        }
    }

    /** Evaluates AD's IN_CHAIN and userAccountControl bit rules the production code sends. */
    private static final class AdRules extends InMemoryOperationInterceptor {
        volatile InMemoryDirectoryServer server;

        @Override
        public void processSearchRequest(InMemoryInterceptedSearchRequest request) throws LDAPException {
            Filter original = request.getRequest().getFilter();
            Filter rewritten = rewrite(original);
            if (rewritten != original) {
                SearchRequest copy = request.getRequest().duplicate();
                copy.setFilter(rewritten);
                request.setRequest(copy);
            }
        }

        private Filter rewrite(Filter filter) throws LDAPException {
            switch (filter.getFilterType()) {
                case Filter.FILTER_TYPE_AND, Filter.FILTER_TYPE_OR -> {
                    Filter[] parts = filter.getComponents();
                    Filter[] out = new Filter[parts.length];
                    boolean changed = false;
                    for (int i = 0; i < parts.length; i++) {
                        out[i] = rewrite(parts[i]);
                        changed |= out[i] != parts[i];
                    }
                    if (!changed) return filter;
                    return filter.getFilterType() == Filter.FILTER_TYPE_AND ? Filter.createANDFilter(out) : Filter.createORFilter(out);
                }
                case Filter.FILTER_TYPE_NOT -> {
                    Filter inner = rewrite(filter.getNOTComponent());
                    return inner == filter.getNOTComponent() ? filter : Filter.createNOTFilter(inner);
                }
                case Filter.FILTER_TYPE_EXTENSIBLE_MATCH -> {
                    if ("1.2.840.113556.1.4.1941".equals(filter.getMatchingRuleID())) {
                        java.util.List<Filter> any = new java.util.ArrayList<>();
                        java.util.Set<String> seen = new java.util.LinkedHashSet<>();
                        java.util.List<String> frontier = new java.util.ArrayList<>(java.util.List.of(filter.getAssertionValue()));
                        any.add(Filter.createEqualityFilter("member", filter.getAssertionValue()));
                        while (!frontier.isEmpty()) {
                            String next = frontier.remove(0);
                            for (var entry : server.search(BASE_DN, com.unboundid.ldap.sdk.SearchScope.SUB,
                                    Filter.createEqualityFilter("member", next)).getSearchEntries()) {
                                if (seen.add(entry.getDN())) {
                                    frontier.add(entry.getDN());
                                    any.add(Filter.createEqualityFilter("member", entry.getDN()));
                                }
                            }
                        }
                        return Filter.createORFilter(any);
                    }
                    if ("1.2.840.113556.1.4.803".equals(filter.getMatchingRuleID())) {
                        return Filter.createEqualityFilter("userAccountControl", "514");
                    }
                    throw new LDAPException(com.unboundid.ldap.sdk.ResultCode.INAPPROPRIATE_MATCHING);
                }
                default -> {
                    return filter;
                }
            }
        }
    }

    /**
     * Stops accepting connections and closes every existing one — used by
     * the directory-unreachable tests to prove a real connectivity failure
     * (never a stubbed one) against the adapter under test.
     */
    public void stopListening() {
        server.shutDown(true);
    }

    @Override
    public void close() {
        server.shutDown(true);
    }

    private record Material(Path caPem, SSLContext server) {
    }

    /** One synthetic CA and {@code localhost} leaf per test JVM, in a private temporary directory. */
    private static synchronized Material material() {
        if (material != null) {
            return material;
        }
        try {
            Path dir = Files.createTempDirectory("test-ldap-tls");
            char[] pin = UUID.randomUUID().toString().toCharArray();
            Path pinFile = dir.resolve("store-pin");
            Files.writeString(pinFile, new String(pin), StandardCharsets.UTF_8);
            Path root = dir.resolve("root.p12");
            Path caPem = dir.resolve("ca.pem");
            keytool(dir, pinFile, "-genkeypair", "-alias", "ca", "-dname", "CN=Synthetic Test CA", "-keyalg", "RSA",
                    "-keysize", "2048", "-validity", "30", "-ext", "bc=ca:true", "-ext", "ku=keyCertSign",
                    "-keystore", root.toString(), "-storetype", "PKCS12");
            keytool(dir, pinFile, "-exportcert", "-alias", "ca", "-rfc", "-keystore", root.toString(),
                    "-file", caPem.toString());
            Path leaf = dir.resolve("leaf.p12");
            Path csr = dir.resolve("leaf.csr");
            Path signed = dir.resolve("leaf.pem");
            keytool(dir, pinFile, "-genkeypair", "-alias", "server", "-dname", "CN=localhost", "-keyalg", "RSA",
                    "-keysize", "2048", "-ext", "san=dns:localhost", "-keystore", leaf.toString(),
                    "-storetype", "PKCS12");
            keytool(dir, pinFile, "-certreq", "-alias", "server", "-keystore", leaf.toString(),
                    "-file", csr.toString());
            keytool(dir, pinFile, "-gencert", "-alias", "ca", "-keystore", root.toString(), "-infile", csr.toString(),
                    "-outfile", signed.toString(), "-rfc", "-ext", "san=dns:localhost",
                    "-ext", "ku=digitalSignature,keyEncipherment", "-ext", "eku=serverAuth", "-validity", "30");
            keytool(dir, pinFile, "-importcert", "-noprompt", "-alias", "ca", "-file", caPem.toString(),
                    "-keystore", leaf.toString());
            keytool(dir, pinFile, "-importcert", "-alias", "server", "-file", signed.toString(),
                    "-keystore", leaf.toString());
            KeyStore keys = KeyStore.getInstance("PKCS12");
            try (var in = Files.newInputStream(leaf)) {
                keys.load(in, pin);
            }
            KeyManagerFactory managers = KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm());
            managers.init(keys, pin);
            SSLContext context = SSLContext.getInstance("TLS");
            context.init(managers.getKeyManagers(), null, null);
            material = new Material(caPem, context);
            return material;
        } catch (Exception e) {
            throw new IllegalStateException("could not generate the synthetic test directory TLS material", e);
        }
    }

    private static void keytool(Path dir, Path pinFile, String... args) throws Exception {
        List<String> command = new ArrayList<>();
        command.add(Path.of(System.getProperty("java.home"), "bin", "keytool").toString());
        command.addAll(List.of(args));
        command.addAll(List.of("-storepass:file", pinFile.toString()));
        Process process = new ProcessBuilder(command).redirectErrorStream(true)
                .redirectOutput(dir.resolve("keytool.log").toFile()).start();
        if (!process.waitFor(60, TimeUnit.SECONDS) || process.exitValue() != 0) {
            throw new IllegalStateException("keytool failed: " + args[0]);
        }
    }
}
